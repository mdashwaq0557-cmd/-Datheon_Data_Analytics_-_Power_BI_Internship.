# 1. Import libraries
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from IPython.display import display

sns.set_theme(style="whitegrid")
plt.rcParams["figure.figsize"] = (9, 5)

# 2. Load dataset
# Upload telco_customer_churn.csv to Colab first.
FILE_PATH = "/content/telco_customer_churn.csv"
df = pd.read_csv(FILE_PATH)

print("Rows and columns:", df.shape)
display(df.head())
print("\nColumn names:")
print(df.columns.tolist())

# 3. Data quality checks and cleaning
print("Data types and non-null counts:")
df.info()

print("\\nMissing values per column:")
display(df.isna().sum().sort_values(ascending=False).to_frame("Missing values"))

print("Duplicate rows:", df.duplicated().sum())

# Convert TotalCharges to numeric. Blank strings become NaN.
df["TotalCharges"] = pd.to_numeric(df["TotalCharges"], errors="coerce")

# Customer IDs should identify one row per customer.
df = df.drop_duplicates()
print("Rows after removing duplicate rows:", len(df))
print("Missing TotalCharges after conversion:", df["TotalCharges"].isna().sum())

# Do not automatically impute TotalCharges: investigate missing values.
display(df.loc[df["TotalCharges"].isna(), ["customerID", "tenure", "MonthlyCharges", "TotalCharges"]].head(15))

# 4. Overall churn KPIs
df["Churn"] = df["Churn"].astype(str).str.strip()

total_customers = df["customerID"].nunique()
churned_customers = df.loc[df["Churn"].eq("Yes"), "customerID"].nunique()
retained_customers = df.loc[df["Churn"].eq("No"), "customerID"].nunique()
churn_rate = churned_customers / total_customers * 100
retention_rate = retained_customers / total_customers * 100

print(f"Total customers: {total_customers:,}")
print(f"Churned customers: {churned_customers:,}")
print(f"Retained customers: {retained_customers:,}")
print(f"Churn rate: {churn_rate:.2f}%")
print(f"Retention rate: {retention_rate:.2f}%")

plt.figure()
sns.countplot(data=df, x="Churn", order=["No", "Yes"])
plt.title("Customer Churn Counts")
plt.xlabel("Churn status")
plt.ylabel("Number of customers")
plt.show()

# 5. Create tenure cohorts and compare churn
# Cohorts are based on current tenure, not acquisition month.
bins = [0, 12, 24, 48, 60, np.inf]
labels = ["0–12 months", "13–24 months", "25–48 months", "49–60 months", "61+ months"]
df["TenureCohort"] = pd.cut(
    df["tenure"], bins=bins, labels=labels, include_lowest=True, right=True
)

cohort = df.groupby("TenureCohort", observed=False).agg(
    Customers=("customerID", "nunique"),
    Churned=("Churn", lambda s: s.eq("Yes").sum())
)
cohort["Retained"] = cohort["Customers"] - cohort["Churned"]
cohort["ChurnRatePct"] = cohort["Churned"] / cohort["Customers"].replace(0, np.nan) * 100
cohort["RetentionRatePct"] = 100 - cohort["ChurnRatePct"]
display(cohort.round(2))

cohort[["ChurnRatePct", "RetentionRatePct"]].plot(kind="bar", figsize=(10, 5))
plt.title("Churn and Retention by Current Tenure Cohort")
plt.ylabel("Percent of customers")
plt.xlabel("Current tenure cohort")
plt.xticks(rotation=25, ha="right")
plt.tight_layout()
plt.show()

# 6. Churn by contract type
contract = df.groupby("Contract", observed=False).agg(
    Customers=("customerID", "nunique"),
    Churned=("Churn", lambda s: s.eq("Yes").sum())
)
contract["ChurnRatePct"] = contract["Churned"] / contract["Customers"] * 100
display(contract.sort_values("ChurnRatePct", ascending=False).round(2))

sns.barplot(data=contract.reset_index(), x="Contract", y="ChurnRatePct")
plt.title("Churn Rate by Contract Type")
plt.ylabel("Churn rate (%)")
plt.xlabel("Contract type")
plt.xticks(rotation=15)
plt.tight_layout()
plt.show()

# 7. Churn by payment method
payment = df.groupby("PaymentMethod", observed=False).agg(
    Customers=("customerID", "nunique"),
    Churned=("Churn", lambda s: s.eq("Yes").sum())
)
payment["ChurnRatePct"] = payment["Churned"] / payment["Customers"] * 100
display(payment.sort_values("ChurnRatePct", ascending=False).round(2))

sns.barplot(data=payment.reset_index(), x="PaymentMethod", y="ChurnRatePct")
plt.title("Churn Rate by Payment Method")
plt.ylabel("Churn rate (%)")
plt.xlabel("Payment method")
plt.xticks(rotation=25, ha="right")
plt.tight_layout()
plt.show()

# 8. Churn by internet service and technical support
for col in ["InternetService", "TechSupport", "OnlineSecurity"]:
    summary = df.groupby(col, dropna=False, observed=False).agg(
        Customers=("customerID", "nunique"),
        ChurnRatePct=("Churn", lambda s: s.eq("Yes").mean() * 100)
    ).sort_values("ChurnRatePct", ascending=False)
    print(f"\\nChurn by {col}:")
    display(summary.round(2))

# Heatmap of churn rate by internet service and tech support
heat = df.pivot_table(
    index="InternetService", columns="TechSupport",
    values="Churn", aggfunc=lambda s: s.eq("Yes").mean() * 100,
    observed=False
)
plt.figure(figsize=(8, 4))
sns.heatmap(heat, annot=True, fmt=".1f", cmap="YlOrRd")
plt.title("Churn Rate (%) by Internet Service and Tech Support")
plt.xlabel("Tech support")
plt.ylabel("Internet service")
plt.tight_layout()
plt.show()

# 9. Churn by monthly charge bands
df["MonthlyChargeBand"] = pd.cut(
    df["MonthlyCharges"],
    bins=[0, 35, 65, 90, np.inf],
    labels=["Up to $35", "$35–$65", "$65–$90", "Above $90"],
    include_lowest=True
)
charges = df.groupby("MonthlyChargeBand", observed=False).agg(
    Customers=("customerID", "nunique"),
    ChurnRatePct=("Churn", lambda s: s.eq("Yes").mean() * 100),
    AverageMonthlyCharge=("MonthlyCharges", "mean")
)
display(charges.round(2))

sns.barplot(data=charges.reset_index(), x="MonthlyChargeBand", y="ChurnRatePct")
plt.title("Churn Rate by Monthly Charge Band")
plt.xlabel("Monthly charge band")
plt.ylabel("Churn rate (%)")
plt.tight_layout()
plt.show()

# 10. Summary table of key churn drivers
segment_columns = ["Contract", "PaymentMethod", "InternetService", "TechSupport", "OnlineSecurity", "PaperlessBilling"]
summaries = []
for col in segment_columns:
    temp = df.groupby(col, dropna=False, observed=False).agg(
        Customers=("customerID", "nunique"),
        Churned=("Churn", lambda s: s.eq("Yes").sum())
    ).reset_index()
    temp["ChurnRatePct"] = temp["Churned"] / temp["Customers"] * 100
    temp.insert(0, "Segment variable", col)
    temp = temp.rename(columns={col: "Segment"})
    summaries.append(temp[["Segment variable", "Segment", "Customers", "Churned", "ChurnRatePct"]])

driver_summary = pd.concat(summaries, ignore_index=True)
display(driver_summary.sort_values("ChurnRatePct", ascending=False).round(2))

